#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

grep -q 'release)' "$ROOT/planer"
test -x "$ROOT/scripts/release.sh"
grep -q 'npm run release' "$ROOT/scripts/release.sh"
grep -q 'cleanup-build-artifacts.sh' "$ROOT/scripts/build-production.sh"
! grep -q 'build-production.sh' "$ROOT/scripts/release.sh"
! grep -q "\['dev', 'manual', 'all'\]" "$ROOT/src/scripts/release.js"
! grep -q 'manual:deploy' "$ROOT/src/scripts/release.js"
grep -q 'git -C "\$ROOT" push origin main "\$tag"' "$ROOT/scripts/release.sh"
grep -q "'src/CHANGELOG.md'" "$ROOT/src/scripts/release.js"
grep -q "'src/package.json'" "$ROOT/src/scripts/release.js"
grep -q "'src/package-lock.json'" "$ROOT/src/scripts/release.js"
grep -q 'pfarrtools/pfarrplaner:vVERSION' "$ROOT/docs/admin/installation-und-migration.md"
grep -q 'pfarrtools/pfarrplaner:vVERSION' "$ROOT/docs/manual/technikhandbuch/deployment.md"

test ! -e "$ROOT/src/scripts/docker-build.js"
test ! -e "$ROOT/src/.woodpecker.yml"
test ! -e "$ROOT/src/Dockerfile"
test ! -e "$ROOT/src/compose.dev.yaml"
! grep -q 'docker:build' "$ROOT/src/package.json"
! grep -q 'docker-build.js' "$ROOT/src/scripts/release.js"
grep -q 'src/vendor' "$ROOT/.dockerignore"
grep -q 'backups' "$ROOT/.dockerignore"
grep -q '^  push:' "$ROOT/.github/workflows/quality.yml"
grep -q '^  pull_request:' "$ROOT/.github/workflows/quality.yml"
grep -q '^          targets: |' "$ROOT/.github/workflows/quality.yml"
grep -q '^            app$' "$ROOT/.github/workflows/quality.yml"
grep -q '^            vite$' "$ROOT/.github/workflows/quality.yml"
grep -q 'run: ./planer dev quality' "$ROOT/.github/workflows/quality.yml"
grep -q 'run: ./planer dev test' "$ROOT/.github/workflows/quality.yml"
grep -q 'if: always()' "$ROOT/.github/workflows/quality.yml"
test -f "$ROOT/.github/workflows/release.yml"
grep -q "tags:" "$ROOT/.github/workflows/release.yml"
grep -q "'v\*'" "$ROOT/.github/workflows/release.yml"
grep -q 'docker/login-action' "$ROOT/.github/workflows/release.yml"
grep -q 'DOCKERHUB_USERNAME' "$ROOT/.github/workflows/release.yml"
grep -q 'DOCKERHUB_TOKEN' "$ROOT/.github/workflows/release.yml"
grep -q 'webfactory/ssh-agent' "$ROOT/.github/workflows/release.yml"
grep -q 'MANUAL_DEPLOY_SSH_KEY' "$ROOT/.github/workflows/release.yml"
grep -q 'MANUAL_DEPLOY_KNOWN_HOSTS' "$ROOT/.github/workflows/release.yml"
grep -q './planer dev manual all' "$ROOT/.github/workflows/release.yml"
grep -q './planer dev manual deploy' "$ROOT/.github/workflows/release.yml"
grep -q 'build-production.sh.*--push' "$ROOT/.github/workflows/release.yml"
grep -q 'PFARRPLANER_IMAGE_REPOSITORY' "$ROOT/.github/workflows/release.yml"
grep -q './planer dev down -v' "$ROOT/.github/workflows/release.yml"

echo 'Release process tests passed'
