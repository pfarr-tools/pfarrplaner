#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
grep -q "listen = 9000" "$ROOT/Dockerfile"
grep -q "clear_env = no" "$ROOT/Dockerfile"
grep -q "catch_workers_output = yes" "$ROOT/Dockerfile"
grep -q "php8.4-posix" "$ROOT/Dockerfile"
grep -q 'php artisan config:clear' "$ROOT/Dockerfile"
grep -q 'php artisan permission:cache-reset' "$ROOT/Dockerfile"
grep -q 'chown -R www-data:www-data /var/www/html/storage/framework /var/www/html/storage/logs /var/www/html/bootstrap/cache' "$ROOT/Dockerfile"
grep -q 'pfarrplaner-app-entrypoint' "$ROOT/compose.yaml"
grep -q 'vendor:/var/www/html/vendor' "$ROOT/compose.yaml"
grep -q 'opt/pfarrplaner-vendor' "$ROOT/Dockerfile"
grep -q 'composer_lock_hash=' "$ROOT/Dockerfile"
grep -q 'composer install --no-interaction --prefer-dist --no-scripts --no-progress' "$ROOT/Dockerfile"
grep -q 'composer-sync.lock' "$ROOT/Dockerfile"
grep -q 'opt/pfarrplaner-node-modules' "$ROOT/Dockerfile"
grep -q 'pfarrplaner-vite-entrypoint' "$ROOT/compose.yaml"
grep -q 'rm -f /app/public/hot' "$ROOT/Dockerfile"
grep -q 'chmod 666 storage/logs/query.log' "$ROOT/planer"
grep -q 'compose exec --user www-data' "$ROOT/planer"
grep -q "env('CACHE_STORE', env('CACHE_DRIVER', 'file'))" "$ROOT/src/config/cache.php"
test -f "$ROOT/src/database/migrations/2014_10_12_200000_create_sessions_table.php"
grep -q -- "--requirepass" "$ROOT/compose.yaml"
grep -Fq 'redis-cli -a \"$$REDIS_PASSWORD\" ping' "$ROOT/compose.yaml"
redis_block="$(sed -n '/^  redis:/,/^  minio:/p' "$ROOT/compose.yaml")"
grep -q 'REDIS_PASSWORD: \${REDIS_PASSWORD:-pfarrplaner-development-redis}' <<<"$redis_block"
grep -q -- '--max_allowed_packet=256M' "$ROOT/compose.yaml"
grep -q 'command: \["php", "artisan", "horizon"\]' "$ROOT/compose.yaml"
grep -q 'grep --line-buffered -vE' "$ROOT/compose.yaml"
grep -Fq '^[[:space:]]*$' "$ROOT/compose.yaml"
grep -q 'command: php artisan horizon' "$ROOT/compose.production.yaml"
grep -q 'grep --line-buffered -vE' "$ROOT/compose.production.yaml"
grep -Fq '^[[:space:]]*$' "$ROOT/compose.production.yaml"
grep -q '"laravel/horizon": "\^5"' "$ROOT/src/composer.json"
test -f "$ROOT/src/config/horizon.php"
echo 'Development runtime tests passed'
