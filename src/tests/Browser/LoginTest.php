<?php

namespace Tests\Browser;

use App\Models\People\User;
use Illuminate\Support\Str;
use Laravel\Dusk\Browser;
use Tests\AbstractPageLoadTest;

class LoginTest extends AbstractPageLoadTest
{
    /** @var User */
    protected $testUser;

    /** @var string */
    protected $password;

    /**
     * Test if the login screen is visible and contains the necessary form
     */
    public function test_login_screen_visible(): void
    {
        $this->browse(function (Browser $browser) {
            $browser->visit('/login')
                ->assertSeeIn('h1', config('app.name'))
                ->assertSee('E-Mailadresse')
                ->assertSee('Passwort')
                ->assertSee('Anmelden');
        });
    }

    public function test_login_works(): void
    {
        $this->browse(function (Browser $browser) {
            $browser->visit('/')
                ->waitFor('[name="email"]')
                ->type('[name="email"]', $this->testUser->email)
                ->type('[name="password"]', $this->password)
                ->press('Anmelden')
                ->waitForLocation('/')
                ->assertRouteIs('home');
        });
    }

    protected function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub

        $this->password = Str::random(16);
        $this->testUser = User::factory()->create(['password' => $this->password]);
    }
}
